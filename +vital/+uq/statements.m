function S = statements(kind)
%STATEMENTS  The explicit statements of the M8 report (amendment R5; review R5
%   m1, m4, m6, m10 and M2): the judgments the analysis rests on and the limits
%   of what it shows. Printed verbatim by vital.uq.headline / writeReport, and
%   the judgments are carried by vital.uq.loadSpec (spec.judgments).
%   S = vital.uq.statements('judgments')    cellstr
%   S = vital.uq.statements('limits')       cellstr
%   Errors: vital:badInput (another kind).
arguments
    kind (1,:) char
end
switch kind
    case 'judgments'
        S = {['JUDGMENT: Cm_basic and Cm_de are treated as independent, although both come from one wind-tunnel ' ...
              'table (cmt): the split (amendment R4-5) is an aero-database build-up, and a correlation between ' ...
              'the static part and the elevator increment is not modelled.'], ...
             ['PRECONDITION: every assessed condition is a 1-g, wings-level, gamma = 0, beta = 0 trim; the ' ...
              'longitudinal-only search (R3-M3(a)) and the lateral groups without Cm_q (R4-9) rely on it, and ' ...
              'their runtime gates check one point per group (the critical condition) only. A turning or ' ...
              'sideslipping condition would invalidate both.'], ...
             ['JUDGMENT: the multipliers are independent normal N(1, sigma) with the JUDGMENT sigmas; the CSR ' ...
              'headline does not depend on this distribution, only the Monte Carlo and the k_g box do.']};
    case 'limits'
        S = {['LIMIT: the lattice certificate is a Lipschitz ESTIMATE from measured secants (grid-certified ' ...
              '(Lipschitz estimate)), not a proof: a feature narrower than a lattice cell (a notch or a band ' ...
              'between the vertices, which no vertex and no neighbouring edge sees) is invisible to it.'], ...
             ['The certified bound of a cell is its minimum vertex margin minus sum_i L_i h_i/2 (h/2: every ' ...
              'point of a cell lies within half an edge of a vertex along each axis), L = 2 x the measured local ' ...
              'slopes (own edges and the 3^d base neighbourhood; amendment R5-1).'], ...
             ['The margins are discontinuous where a trim alpha or elevator crosses a NESC aero-table breakpoint ' ...
              '(e.g. alpha = 5 deg): a cell whose vertices trim on both sides is certified piecewise, each side ' ...
              'from its own vertices with the full edge h and slopes measured away from the jump (amendment ' ...
              'R5-3); R4-7 bracketing only treats a linearization AT a breakpoint.'], ...
             ['The worse of the two one-sided linearizations of a BRACKETED point is an engineering rule, not a ' ...
              'bound for the switched system; the sides theta x (1 -/+ d) scale every parameter, so a side may ' ...
              'lie up to 1 % outside the box. The fresh confirmations are not bracketed: one at a breakpoint is ' ...
              'NOT_OK, never a pass.'], ...
             ['The Monte Carlo runs at the group''s nominal critical condition only: its Clopper-Pearson bound ' ...
              'is a per-condition success probability, not an in-envelope one.'], ...
             ['SCOPE: the lattice certificate and the CSR cover the group''s candidate conditions only; the ' ...
              'other in-envelope conditions are checked by fresh full assessments at the CPV, at the box ' ...
              'arg-mins and at the 2^d corners of R(1) and of R(alphaLo), where a smaller margin overrides the ' ...
              'lattice as a moving limit (amendment R5-5, M2).'], ...
             ['R5 verdict: ROBUST = every lattice cell (longitudinal groups) or the box search (other groups) ' ...
              'meeting the judged box R(1) certified >= 0, i.e. alphaLo >= 1 with R(alphaLo) certified, AND the ' ...
              'Clopper-Pearson lower bound >= 0.95; alpha* is reported as the bracket [alphaLo, alphaHi] (0.01 ' ...
              'is required for the judged shape only); NOT_ROBUST = a confirmed CPV with scaled norm <= 1 OR the ' ...
              'lower bound below 0.95; NOT_ASSESSABLE = anything else.']};
    otherwise
        error('vital:badInput', 'statements: kind must be ''judgments'' or ''limits'' (got ''%s'').', kind);
end
end
