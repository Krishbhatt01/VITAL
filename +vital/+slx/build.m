function s = build(opts)
%BUILD  Generate the VitalPlant Simulink model from scratch (docs/PLAN_M9.md
%   sections 2 and 4, ADR-039). The .slx is a GENERATED artifact: never edit it by
%   hand; change this script and regenerate (tests/M9/tSlxBuild.m compares the
%   committed models/VitalPlant.slx with a fresh build).
%
%   s = vital.slx.build()                    writes models/VitalPlant.slx
%   s = vital.slx.build('Folder', f)         writes f/VitalPlant.slx
%   s is vital.slx.structure of the model (blocks, lines, solver, text, hash).
%
%   Blocks: Plant (MATLAB Function, continuous: xdot = kernel('plant', x, u)),
%   Integrator (13 states, initial condition variable x0), FCS (MATLAB Function,
%   discrete, sample time variable Ts: u = kernel('fcs', t, x)), Clock (Digital
%   Clock, Ts), Outports x and u. Solver: Fixed-step ode4, FixedStep variable dt.
%   The variables x0, dt, Ts and the stop time are set per run by vital.slx.simulate.
arguments
    opts.Folder (1,:) char = ''
end
name = 'VitalPlant';
if isempty(opts.Folder), opts.Folder = fileparts(vital.slx.modelFile()); end
if ~isfolder(opts.Folder), mkdir(opts.Folder); end
file = fullfile(opts.Folder, [name '.slx']);
if bdIsLoaded(name), close_system(name, 0); end
new_system(name);
cleanup = onCleanup(@() closeIfLoaded(name));
m = name;

% ---- blocks (fixed positions: a deterministic layout) -----------------------------
add_block('simulink/Sources/Digital Clock', [m '/Clock'], 'SampleTime', 'Ts', ...
    'Position', [40 40 100 70]);
add_block('simulink/User-Defined Functions/MATLAB Function', [m '/FCS'], ...
    'Position', [160 30 260 110]);
add_block('simulink/User-Defined Functions/MATLAB Function', [m '/Plant'], ...
    'Position', [320 30 420 110]);
add_block('simulink/Continuous/Integrator', [m '/Integrator'], 'InitialCondition', 'x0', ...
    'Position', [480 55 520 85]);
add_block('simulink/Sinks/Out1', [m '/x'], 'Port', '1', 'Position', [600 63 630 77]);
add_block('simulink/Sinks/Out1', [m '/u'], 'Port', '2', 'Position', [600 133 630 147]);

% ---- MATLAB Function code (one physics source: vital.slx.kernel -> vital.plant.derivatives)
setChart(m, 'Plant', plantScript(), '-1');
setChart(m, 'FCS', fcsScript(), 'Ts');

% ---- wiring ----------------------------------------------------------------------
add_line(m, 'Clock/1', 'FCS/1', 'autorouting', 'on');
add_line(m, 'Integrator/1', 'FCS/2', 'autorouting', 'on');
add_line(m, 'Integrator/1', 'Plant/1', 'autorouting', 'on');
add_line(m, 'Integrator/1', 'x/1', 'autorouting', 'on');
add_line(m, 'FCS/1', 'Plant/2', 'autorouting', 'on');
add_line(m, 'FCS/1', 'u/1', 'autorouting', 'on');
add_line(m, 'Plant/1', 'Integrator/1', 'autorouting', 'on');

% ---- solver and logging --------------------------------------------------------
set_param(m, 'SolverType', 'Fixed-step', 'Solver', 'ode4', 'FixedStep', 'dt', ...
    'StartTime', '0', 'StopTime', '1', ...
    'SaveTime', 'on', 'TimeSaveName', 'tout', 'SaveOutput', 'on', 'OutputSaveName', 'yout', ...
    'SaveFormat', 'StructureWithTime', 'SaveState', 'off', 'SignalLogging', 'off', ...
    'LimitDataPoints', 'off', 'Decimation', '1', 'ReturnWorkspaceOutputs', 'on', ...
    'AlgebraicLoopMsg', 'error');
save_system(m, file);
s = vital.slx.structure(m);
s.file = file;
end

function setChart(m, blk, script, ts)
rt = sfroot;
ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', [m '/' blk]);
ch.Script = script;
set_param([m '/' blk], 'SystemSampleTime', ts);   % EMChart.SampleTime does not keep a variable name
end

function t = plantScript()
t = sprintf(['function xdot = Plant(x, u)\n' ...
    '%% GENERATED by vital.slx.build: the continuous plant (vital.plant.derivatives via vital.slx.kernel).\n' ...
    'coder.extrinsic(''vital.slx.kernel'');\n' ...
    'xdot = zeros(13, 1);\n' ...
    'xdot = vital.slx.kernel(''plant'', x, u);\n']);
end

function t = fcsScript()
t = sprintf(['function u = FCS(t, x)\n' ...
    '%% GENERATED by vital.slx.build: the discrete FCS / input sample (zero-order held by Simulink).\n' ...
    'coder.extrinsic(''vital.slx.kernel'');\n' ...
    'u = zeros(4, 1);\n' ...
    'u = vital.slx.kernel(''fcs'', t, x);\n']);
end

function closeIfLoaded(name)
if bdIsLoaded(name), close_system(name, 0); end
end
